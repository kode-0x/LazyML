"""HTML report generation."""

import json
from pathlib import Path
from typing import Any
from datetime import datetime

import pandas as pd


class ReportGenerator:
    """Generate HTML and JSON reports."""

    def __init__(self, output_dir: Path) -> None:
        self.output_dir = Path(output_dir)

    def generate(
        self,
        df: pd.DataFrame,
        target_column: str,
        task_type: str,
        leaderboard: list[dict[str, Any]],
        best_model_name: str,
    ) -> None:
        """Generate all reports."""
        self._generate_html(df, target_column, task_type, leaderboard, best_model_name)
        self._generate_json(leaderboard)

    def _generate_html(
        self,
        df: pd.DataFrame,
        target_column: str,
        task_type: str,
        leaderboard: list[dict[str, Any]],
        best_model_name: str,
    ) -> None:
        """Generate HTML report."""
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        # Dataset summary
        n_rows, n_columns = df.shape

        # Build leaderboard HTML
        leaderboard_rows = ""
        for entry in leaderboard:
            if task_type == "classification":
                metrics = f"{entry.get('accuracy', 0):.4f}"
                metric_name = "Accuracy"
            else:
                metrics = f"{entry.get('r2', 0):.4f}"
                metric_name = "R²"

            leaderboard_rows += f"""
                <tr>
                    <td>{entry['model']}</td>
                    <td>{metrics}</td>
                    <td>{entry.get('cv_std', 0):.4f}</td>
                    <td>{entry['train_time']:.2f}s</td>
                </tr>
            """

        html = f"""<!DOCTYPE html>
<html>
<head>
    <title>LazyML Report</title>
    <style>
        body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; max-width: 900px; margin: 0 auto; padding: 20px; line-height: 1.6; }}
        h1, h2 {{ color: #333; }}
        table {{ border-collapse: collapse; width: 100%; margin: 20px 0; }}
        th, td {{ padding: 12px; text-align: left; border-bottom: 1px solid #ddd; }}
        th {{ background-color: #4CAF50; color: white; }}
        tr:hover {{ background-color: #f5f5f5; }}
        .metric {{ display: inline-block; padding: 10px 20px; margin: 10px; background: #f0f0f0; border-radius: 5px; }}
        .metric-value {{ font-size: 24px; font-weight: bold; color: #4CAF50; }}
        .winner {{ background: #e8f5e9; border-left: 4px solid #4CAF50; padding: 15px; margin: 20px 0; }}
        code {{ background: #f4f4f4; padding: 2px 6px; border-radius: 3px; }}
    </style>
</head>
<body>
    <h1>LazyML Report</h1>
    <p>Generated: {timestamp}</p>

    <div class="winner">
        <strong>Best Model: {best_model_name}</strong>
    </div>

    <h2>Dataset Summary</h2>
    <div class="metric">
        Rows<br><span class="metric-value">{n_rows:,}</span>
    </div>
    <div class="metric">
        Columns<br><span class="metric-value">{n_columns}</span>
    </div>
    <div class="metric">
        Task Type<br><span class="metric-value">{task_type.title()}</span>
    </div>
    <div class="metric">
        Target<br><span class="metric-value">{target_column}</span>
    </div>

    <h2>Model Leaderboard</h2>
    <table>
        <thead>
            <tr>
                <th>Model</th>
                <th>{metric_name}</th>
                <th>CV Std</th>
                <th>Train Time</th>
            </tr>
        </thead>
        <tbody>
            {leaderboard_rows}
        </tbody>
    </table>

    <h2>Output Files</h2>
    <ul>
        <li><code>model.pkl</code> - Trained model with preprocessor</li>
        <li><code>preprocessor.pkl</code> - Fitted preprocessing pipeline</li>
        <li><code>leaderboard.json</code> - Model rankings (JSON)</li>
    </ul>

    <footer style="margin-top: 40px; padding-top: 20px; border-top: 1px solid #ddd; color: #666; font-size: 12px;">
        Generated by LazyML
    </footer>
</body>
</html>"""

        report_path = self.output_dir / "report.html"
        report_path.write_text(html, encoding="utf-8")
        print(f"Report saved: {report_path}")

    def _generate_json(self, leaderboard: list[dict[str, Any]]) -> None:
        """Generate JSON leaderboard."""
        # Remove model objects from JSON
        json_leaderboard = []
        for entry in leaderboard:
            json_entry = {k: v for k, v in entry.items() if k != "model"}
            json_entry["model_name"] = entry["model"]
            json_leaderboard.append(json_entry)

        json_path = self.output_dir / "leaderboard.json"
        json_path.write_text(json.dumps(json_leaderboard, indent=2), encoding="utf-8")
        print(f"Leaderboard saved: {json_path}")
